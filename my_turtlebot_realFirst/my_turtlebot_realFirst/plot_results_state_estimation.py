"""
================================================================================
PROJECT: Multi-Robot Tracking Analysis
SCRIPT: Plotting & Performance Evaluation
================================================================================
DESCRIPTION:
    This script processes the CSV data generated by the Kalman Observer node.
    It performs three main tasks:
    1. ALIGNMENT: Shifts Ground Truth (OptiTrack) data to match the initial 
       relative offset between TB1 and TB2.
    2. VISUALIZATION: Plots the physical footprint of TB1 and compares the 
       Odometry, LiDAR, and Kalman Filter trajectories.
    3. EVALUATION: Computes Root Mean Square Error (RMSE) for both the raw 
       odometry and the fused Kalman estimate to determine improvement.
================================================================================
"""

import matplotlib.pyplot as plt
import matplotlib.patches as patches
import pandas as pd
import numpy as np
import os

def plot_trajectories(csv_file):
    # Verify the file exists before attempting to load
    if not os.path.exists(csv_file):
        print(f"Error: {csv_file} not found! Check your path.")
        return

    # Load experimental data into a Pandas DataFrame
    data = pd.read_csv(csv_file)
    
    # --- PHYSICAL COORDINATE ALIGNMENT ---
    # TB1 is at the origin (0,0). TB2 starts at this specific offset:
    tb2_initial_x = 0.42
    tb2_initial_y = 0.006
    
    # Capture the very first frame of OptiTrack data to find the offset
    opti_start_x = data['opti_x'].iloc[0]
    opti_start_y = data['opti_y'].iloc[0]
    
    # Align Ground Truth: Shift OptiTrack points so the trajectory starts 
    # at our defined initial relative position.
    data['opti_x_aligned'] = (data['opti_x'] - opti_start_x) + tb2_initial_x
    data['opti_y_aligned'] = (data['opti_y'] - opti_start_y) + tb2_initial_y
    
    # Map raw data columns for cleaner plotting logic
    data['kf_x_clean'] = data['kf_x']
    data['kf_y_clean'] = data['kf_y']
    data['odom_x_clean'] = data['odom_x']
    data['odom_y_clean'] = data['odom_y']
    data['lidar_x_clean'] = data['lidar_x']
    data['lidar_y_clean'] = data['lidar_y']

    # Initialize the plot with specific dimensions
    fig, ax = plt.subplots(figsize=(12, 8))
    
    # --- PLOTTING ROBOT FOOTPRINT ---
    # Radius set to 0.105m to visualize the physical footprint of the TurtleBot
    robot_radius = 0.105 
    
    # Draw TB1's physical body at the origin to give a sense of scale to the error
    tb1_body = patches.Circle((0, 0), robot_radius, color='magenta', alpha=0.2, label='TB1 Physical Size')
    ax.add_patch(tb1_body)
    
    # Mark the precise center of the Observer (TB1)
    ax.plot(0, 0, 'ms', markersize=10, label='TB1 Observer (Origin)')
    
    # --- PLOTTING TRAJECTORIES ---
    # 1. Aligned Ground Truth (Solid Black line - the path the robot actually took)
    ax.plot(data['opti_x_aligned'], data['opti_y_aligned'], 'k-', linewidth=3, label='Ground Truth (OptiTrack)')
    
    # 2. Raw Odometry (Dashed Red line - showing the cumulative wheel drift)
    ax.plot(data['odom_x_clean'], data['odom_y_clean'], 'r--', label='Odometry (Drifted)', alpha=0.7)
    
    # 3. Raw LiDAR points (Blue Scatter - showing sensor noise/jitter)
    ax.scatter(data['lidar_x_clean'], data['lidar_y_clean'], c='blue', s=8, label='Raw LIDAR (Noisy)', alpha=0.4)
    
    # 4. Fused Kalman Filter (Solid Green line - the optimized estimate)
    ax.plot(data['kf_x_clean'], data['kf_y_clean'], 'g-', linewidth=2.5, label='Kalman Filter (Fused)')

    # Formatting the visual graph
    ax.set_title('Multi-Robot Tracking: Robot 2 Position Relative to Robot 1', fontsize=14)
    ax.set_xlabel('X Position relative to TB1 (meters)', fontsize=12)
    ax.set_ylabel('Y Position relative to TB1 (meters)', fontsize=12)
    ax.legend(loc='upper right', fontsize=10)
    ax.grid(True, linestyle=':', alpha=0.6)
    ax.axis('equal') # Maintain 1:1 aspect ratio for accurate distance visualization
    
    # --- Performance Metrics Calculation (RMSE) ---
    # Calculate Euclidean distance between KF and Ground Truth for every point
    kf_error = np.sqrt((data['kf_x_clean'] - data['opti_x_aligned'])**2 + 
                       (data['kf_y_clean'] - data['opti_y_aligned'])**2)
    rmse_kf = np.sqrt(np.mean(kf_error**2)) # Root Mean Square calculation
    
    # Calculate Euclidean distance between Odometry and Ground Truth for every point
    odom_error = np.sqrt((data['odom_x_clean'] - data['opti_x_aligned'])**2 + 
                         (data['odom_y_clean'] - data['opti_y_aligned'])**2)
    rmse_odom = np.sqrt(np.mean(odom_error**2))

    # Print summary of results to the console
    print(f"--- Performance Metrics ---")
    print(f"Kalman Filter RMSE: {rmse_kf:.4f} meters")
    print(f"Raw Odometry RMSE:  {rmse_odom:.4f} meters")
    # Calculate percentage reduction in error
    improvement = ((rmse_odom - rmse_kf) / rmse_odom * 100)
    print(f"Improvement:        {improvement:.1f}%")

    # Export final high-resolution figure
    plt.savefig('final_tracking_with_footprint37.png', dpi=300)
    plt.show()

if __name__ == "__main__":
    plot_trajectories('tracking_results_with_optitrack37.csv')